import React, { useEffect, useMemo, useRef, useState } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import {
  X,
  FileText,
  Download,
  Printer,
  Mail,
  CheckCircle2,
  Eye,
  TableProperties
} from 'lucide-react';
import { BuiltMonthlyPdfReport, formatMinutesLabel } from '../src/lib/pdfExport';
import { MonthlyReportRecord } from '../types';

interface PdfViewerModalProps {
  isOpen: boolean;
  onClose: () => void;
  report: BuiltMonthlyPdfReport | null;
  record?: MonthlyReportRecord | null;
  darkMode?: boolean;
  onRequestSendEmail?: () => void;
}

export const PdfViewerModal: React.FC<PdfViewerModalProps> = ({
  isOpen,
  onClose,
  report,
  record,
  darkMode = false,
  onRequestSendEmail
}) => {
  const [viewerTab, setViewerTab] = useState<'pdf' | 'structured'>('pdf');
  const iframeRef = useRef<HTMLIFrameElement | null>(null);

  const blobUrl = useMemo(() => {
    if (!isOpen || !report?.blob) return null;
    return URL.createObjectURL(report.blob);
  }, [isOpen, report]);

  useEffect(() => {
    return () => {
      if (blobUrl) {
        URL.revokeObjectURL(blobUrl);
      }
    };
  }, [blobUrl]);

  useEffect(() => {
    if (isOpen) {
      setViewerTab('pdf');
    }
  }, [isOpen, report?.monthKey]);

  const handlePrint = () => {
    try {
      if (viewerTab === 'pdf' && iframeRef.current?.contentWindow) {
        iframeRef.current.contentWindow.focus();
        iframeRef.current.contentWindow.print();
        return;
      }
    } catch {
      // Fallback to window print if iframe print is restricted
    }
    window.print();
  };

  if (!isOpen || !report) return null;

  const isSent = record?.emailStatus === 'sent';

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-[80] flex items-center justify-center p-2 sm:p-5">
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          onClick={onClose}
          className="absolute inset-0 bg-slate-950/70 backdrop-blur-sm"
        />

        <motion.div
          initial={{ opacity: 0, scale: 0.97, y: 12 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.97, y: 12 }}
          className={`relative w-full max-w-5xl h-[90vh] rounded-[28px] border shadow-2xl flex flex-col overflow-hidden ${
            darkMode
              ? 'bg-slate-900 border-white/10 text-white'
              : 'bg-white border-slate-200 text-slate-900'
          }`}
        >
          {/* Top Header */}
          <div
            className={`px-4 sm:px-6 py-3.5 border-b flex flex-wrap items-center justify-between gap-3 shrink-0 ${
              darkMode ? 'border-white/10 bg-slate-900/95' : 'border-slate-200 bg-slate-50/90'
            }`}
          >
            <div className="flex items-center gap-3 min-w-0">
              <div className="w-10 h-10 rounded-2xl bg-indigo-600/15 text-indigo-500 flex items-center justify-center shrink-0">
                <FileText size={20} />
              </div>
              <div className="min-w-0">
                <div className="flex items-center gap-2 flex-wrap">
                  <h3 className="text-sm sm:text-base font-black tracking-tight truncate">
                    Rapport PDF · {report.monthTitle}
                  </h3>
                  {record?.autoGenerated && (
                    <span className="text-[10px] font-bold px-2 py-0.5 rounded-lg bg-indigo-500/15 text-indigo-500">
                      Auto 1er du mois
                    </span>
                  )}
                  {isSent && (
                    <span className="text-[10px] font-bold px-2 py-0.5 rounded-lg bg-emerald-500/15 text-emerald-500 flex items-center gap-1">
                      <CheckCircle2 size={11} />
                      Envoyé par mail
                    </span>
                  )}
                </div>
                <p className={`text-[11px] truncate ${darkMode ? 'text-slate-400' : 'text-slate-500'}`}>
                  {report.fileName} · {report.periodStartLabel} au {report.periodEndLabel}
                </p>
              </div>
            </div>

            <div className="flex items-center gap-2 flex-wrap">
              {/* View mode toggle */}
              <div
                className={`p-1 rounded-xl border flex items-center gap-1 ${
                  darkMode ? 'bg-slate-800 border-white/10' : 'bg-slate-100 border-slate-200'
                }`}
              >
                <button
                  type="button"
                  onClick={() => setViewerTab('pdf')}
                  className={`px-2.5 py-1.5 rounded-lg text-xs font-bold flex items-center gap-1.5 transition-all ${
                    viewerTab === 'pdf'
                      ? 'bg-indigo-600 text-white shadow-sm'
                      : darkMode
                        ? 'text-slate-300 hover:text-white'
                        : 'text-slate-600 hover:text-slate-900'
                  }`}
                >
                  <Eye size={13} />
                  <span>PDF</span>
                </button>
                <button
                  type="button"
                  onClick={() => setViewerTab('structured')}
                  className={`px-2.5 py-1.5 rounded-lg text-xs font-bold flex items-center gap-1.5 transition-all ${
                    viewerTab === 'structured'
                      ? 'bg-indigo-600 text-white shadow-sm'
                      : darkMode
                        ? 'text-slate-300 hover:text-white'
                        : 'text-slate-600 hover:text-slate-900'
                  }`}
                >
                  <TableProperties size={13} />
                  <span>Détail</span>
                </button>
              </div>

              {onRequestSendEmail && (
                <button
                  type="button"
                  onClick={onRequestSendEmail}
                  className="min-h-[38px] px-3 py-1.5 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold flex items-center gap-1.5 shadow-sm transition-all active:scale-[0.98]"
                >
                  <Mail size={14} />
                  <span>{isSent ? 'Renvoyer par mail' : 'Envoyer par mail'}</span>
                </button>
              )}

              <button
                type="button"
                onClick={handlePrint}
                title="Imprimer le rapport"
                className={`min-h-[38px] px-3 py-1.5 rounded-xl border text-xs font-bold flex items-center gap-1.5 transition-all ${
                  darkMode
                    ? 'bg-white/5 border-white/10 text-slate-200 hover:bg-white/10'
                    : 'bg-white border-slate-200 text-slate-700 hover:bg-slate-50'
                }`}
              >
                <Printer size={14} />
                <span className="hidden sm:inline">Imprimer</span>
              </button>

              {blobUrl && (
                <a
                  href={blobUrl}
                  download={report.fileName}
                  className={`min-h-[38px] px-3 py-1.5 rounded-xl border text-xs font-bold flex items-center gap-1.5 transition-all ${
                    darkMode
                      ? 'bg-white/5 border-white/10 text-slate-200 hover:bg-white/10'
                      : 'bg-white border-slate-200 text-slate-700 hover:bg-slate-50'
                  }`}
                >
                  <Download size={14} />
                  <span className="hidden sm:inline">Télécharger</span>
                </a>
              )}

              <button
                type="button"
                onClick={onClose}
                aria-label="Fermer l'aperçu PDF"
                className={`w-9 h-9 rounded-xl border flex items-center justify-center transition-all ${
                  darkMode
                    ? 'bg-white/5 border-white/10 text-slate-300 hover:text-white'
                    : 'bg-white border-slate-200 text-slate-500 hover:text-slate-900'
                }`}
              >
                <X size={16} />
              </button>
            </div>
          </div>

          {/* Body */}
          <div className={`flex-1 overflow-hidden flex flex-col ${darkMode ? 'bg-slate-950/60' : 'bg-slate-100'}`}>
            {viewerTab === 'pdf' && blobUrl ? (
              <div className="flex-1 flex flex-col p-2 sm:p-4 gap-2 overflow-hidden">
                <iframe
                  ref={iframeRef}
                  src={`${blobUrl}#toolbar=1&navpanes=0`}
                  title={report.fileName}
                  className="w-full flex-1 rounded-2xl border border-slate-200/80 bg-white shadow-inner"
                />
                <div className="flex items-center justify-between gap-2 px-1 text-[11px] text-slate-400">
                  <span>Aperçu natif du fichier PDF ({report.fileName})</span>
                  <button
                    type="button"
                    onClick={() => setViewerTab('structured')}
                    className="text-indigo-500 font-bold hover:underline"
                  >
                    Afficher en vue détaillée
                  </button>
                </div>
              </div>
            ) : (
              <div className="flex-1 overflow-y-auto p-3 sm:p-6">
                <div className="max-w-3xl mx-auto bg-white text-slate-900 rounded-2xl border border-slate-200 shadow-lg p-5 sm:p-8 space-y-6">
                  <div className="border-b border-slate-200 pb-4 flex flex-wrap items-start justify-between gap-3">
                    <div>
                      <p className="text-xs font-black uppercase tracking-widest text-indigo-600">
                        AmbuFlow · Archivage mensuel
                      </p>
                      <h4 className="text-xl font-black text-slate-900 mt-1">
                        Rapport mensuel — {report.monthTitle}
                      </h4>
                      <p className="text-xs text-slate-500 mt-0.5">
                        Période du {report.periodStartLabel} au {report.periodEndLabel}
                      </p>
                    </div>
                    <span className="text-xs text-slate-500 font-medium">
                      {report.generatedAtLabel}
                    </span>
                  </div>

                  {/* Summary KPI grid */}
                  <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
                    <div className="p-3 rounded-xl bg-slate-50 border border-slate-200">
                      <p className="text-[10px] font-bold uppercase text-slate-500">Total effectif</p>
                      <p className="text-lg font-black text-slate-900 mt-0.5">
                        {formatMinutesLabel(report.summary.totalEffectiveMinutes)}
                      </p>
                    </div>
                    <div className="p-3 rounded-xl bg-slate-50 border border-slate-200">
                      <p className="text-[10px] font-bold uppercase text-slate-500">Travail réel</p>
                      <p className="text-lg font-black text-slate-900 mt-0.5">
                        {formatMinutesLabel(report.summary.totalWorkedOnlyMinutes)}
                      </p>
                    </div>
                    <div className="p-3 rounded-xl bg-slate-50 border border-slate-200">
                      <p className="text-[10px] font-bold uppercase text-slate-500">Pauses déduites</p>
                      <p className="text-lg font-black text-slate-900 mt-0.5">
                        {formatMinutesLabel(report.summary.totalBreakDeductedMinutes)}
                      </p>
                    </div>
                    <div className="p-3 rounded-xl bg-slate-50 border border-slate-200">
                      <p className="text-[10px] font-bold uppercase text-slate-500">Gardes / Congés</p>
                      <p className="text-lg font-black text-slate-900 mt-0.5">
                        {report.summary.workShiftCount} g · {report.summary.cpDaysCount + report.summary.ferieDaysCount} j
                      </p>
                    </div>
                  </div>

                  {/* Vehicles */}
                  <div>
                    <h5 className="text-xs font-black uppercase tracking-wider text-slate-700 mb-2">
                      Répartition par type de véhicule
                    </h5>
                    <div className="overflow-x-auto border border-slate-200 rounded-xl">
                      <table className="w-full text-xs text-left">
                        <thead className="bg-indigo-600 text-white">
                          <tr>
                            <th className="px-3 py-2 font-bold">Véhicule</th>
                            <th className="px-3 py-2 font-bold text-center">Gardes</th>
                            <th className="px-3 py-2 font-bold text-right">Heures</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-slate-200">
                          {report.summary.vehicleBreakdown.length === 0 ? (
                            <tr>
                              <td colSpan={3} className="px-3 py-3 text-slate-500 text-center">
                                Aucune mission véhicule sur ce mois
                              </td>
                            </tr>
                          ) : (
                            report.summary.vehicleBreakdown.map((v) => (
                              <tr key={v.vehicle}>
                                <td className="px-3 py-2 font-bold">{v.vehicle}</td>
                                <td className="px-3 py-2 text-center">{v.count}</td>
                                <td className="px-3 py-2 text-right font-bold">
                                  {formatMinutesLabel(v.minutes)}
                                </td>
                              </tr>
                            ))
                          )}
                        </tbody>
                      </table>
                    </div>
                  </div>

                  {/* Detail table */}
                  <div>
                    <h5 className="text-xs font-black uppercase tracking-wider text-slate-700 mb-2">
                      Relevé journalier détaillé
                    </h5>
                    <div className="overflow-x-auto border border-slate-200 rounded-xl">
                      <table className="w-full text-xs text-left">
                        <thead className="bg-slate-900 text-white">
                          <tr>
                            <th className="px-2.5 py-2 font-bold">Date</th>
                            <th className="px-2.5 py-2 font-bold">Véhicule / Type</th>
                            <th className="px-2.5 py-2 font-bold">Horaires</th>
                            <th className="px-2.5 py-2 font-bold">Pauses</th>
                            <th className="px-2.5 py-2 font-bold text-right">Effectif</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-slate-200">
                          {report.detailRows.map((row, idx) => (
                            <tr key={`${row.date}-${idx}`} className={idx % 2 === 1 ? 'bg-slate-50' : 'bg-white'}>
                              <td className="px-2.5 py-2 font-bold whitespace-nowrap">{row.date}</td>
                              <td className="px-2.5 py-2">{row.vehicleOrType}</td>
                              <td className="px-2.5 py-2 whitespace-nowrap">{row.horaires}</td>
                              <td className="px-2.5 py-2 whitespace-pre-line text-slate-600">{row.breaksText}</td>
                              <td className="px-2.5 py-2 text-right font-bold whitespace-nowrap">{row.effective}</td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  </div>
                </div>
              </div>
            )}
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
};
